import { useCallback } from 'react';
import { useAccount, useWalletClient } from 'wagmi';
import { CONTRACTS, CHAIN_ID } from '@/config/contracts';
import type { KYCProof } from './useCrowdfunding';

// EIP-712 Domain for KYC Verifier
const getKYCDomain = (chainId: number) => ({
  name: 'RWA KYC Verifier',
  version: '1',
  chainId,
  verifyingContract: CONTRACTS.KYCVerifier as `0x${string}`,
});

const KYC_TYPES = {
  KYCProof: [
    { name: 'wallet', type: 'address' },
    { name: 'level', type: 'uint8' },
    { name: 'countryCode', type: 'uint16' },
    { name: 'expiry', type: 'uint256' },
  ],
} as const;

export enum KYCLevel {
  NONE = 0,
  BASIC = 1,
  STANDARD = 2,
  ACCREDITED = 3,
  INSTITUTIONAL = 4,
}

export interface KYCData {
  wallet: string;
  level: KYCLevel;
  countryCode: number;
  expiry: bigint;
}

/**
 * Hook for KYC operations
 * 
 * For production:
 * - KYC proofs should be generated by your backend after KYC verification
 * - The backend signs with the trustedSigner private key
 * - Frontend receives the signed proof and passes it to invest()
 */
export function useKYC() {
  const { address } = useAccount();
  const { data: walletClient } = useWalletClient();

  /**
   * Generate KYC proof (FOR TESTING ONLY)
   * In production, this should be done by your backend
   */
  const generateKYCProof = useCallback(async (
    level: KYCLevel = KYCLevel.ACCREDITED,
    countryCode: number = 840, // USA
    expiryHours: number = 24
  ): Promise<KYCProof | null> => {
    if (!walletClient || !address) return null;

    try {
      const expiry = BigInt(Math.floor(Date.now() / 1000) + expiryHours * 3600);
      const chainId = await walletClient.getChainId();

      const signature = await walletClient.signTypedData({
        domain: getKYCDomain(chainId),
        types: KYC_TYPES,
        primaryType: 'KYCProof',
        message: {
          wallet: address,
          level,
          countryCode,
          expiry,
        },
      });

      return {
        level,
        countryCode,
        expiry,
        signature,
      };
    } catch (e) {
      console.error('Error generating KYC proof:', e);
      return null;
    }
  }, [walletClient, address]);

  /**
   * Fetch KYC proof from backend API
   * This is the production approach
   */
  const fetchKYCProof = useCallback(async (): Promise<KYCProof | null> => {
    if (!address) return null;

    try {
      const response = await fetch('/api/kyc/proof', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ wallet: address }),
      });

      if (!response.ok) {
        throw new Error('Failed to fetch KYC proof');
      }

      const data = await response.json();
      return {
        level: data.level,
        countryCode: data.countryCode,
        expiry: BigInt(data.expiry),
        signature: data.signature,
      };
    } catch (e) {
      console.error('Error fetching KYC proof:', e);
      return null;
    }
  }, [address]);

  return {
    generateKYCProof, // Testing only
    fetchKYCProof,    // Production
  };
}
